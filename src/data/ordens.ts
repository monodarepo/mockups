// ── Blocos de sequência (Gantt) ────────────────────────────────────────────

let seqBloco = 0
function bloco(
  linhaId: string,
  tipo: BlocoSequencia['tipo'],
  inicio: Date,
  fim: Date,
  rotulo: string,
  ordemId?: string,
): BlocoSequencia {
  seqBloco += 1
  const base = { id: `BL-${String(seqBloco).padStart(3, '0')}`, linhaId, tipo, rotulo, inicio, fim }
  return ordemId ? { ...base, ordemId } : base
}

